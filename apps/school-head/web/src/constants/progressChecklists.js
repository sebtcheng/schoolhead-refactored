export const getChecklist = (storeys) => {
  const s = parseInt(storeys);
  if (s >= 3) return PROGRESS_CHECKLISTS[3];
  if (s === 2) return PROGRESS_CHECKLISTS[2];
  return PROGRESS_CHECKLISTS[1];
};

export const calcTriangulatedPercentage = (checklistConfig, checkedIds) => {
  if (!checklistConfig || !Array.isArray(checklistConfig) || !checkedIds) return 0;
  const total = checklistConfig.reduce((acc, item) => {
    if (checkedIds[item.id]) {
      return acc + item.weight;
    }
    return acc;
  }, 0);
  return parseFloat(total.toFixed(2));
};
